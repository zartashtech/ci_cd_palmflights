

function confirm() {
    var x = document.forms["search"]["leaving_date"].value;
    var y = document.forms["search"]["trip_type"].value;
    var z = document.forms["search"]["departing_date"].value;

    if (x < z && y == "return") {
        alert("Please select valid Return Date and search again.");
        return false;
    }
    if (x == "" && y == "return") {
        alert("Please select Return Date and search again.");
        return false;
    }
}
